class PostgresEnrollmentTransaction(EnrollmentTransaction):
    def __init__(self, database, *, membership_exchange=None):
        super().__init__(database, '%s')
        self.membership_exchange = membership_exchange

    def paid(self):
        from .paid_postgres import PostgresPaidTransaction
        return PostgresPaidTransaction(self.database, membership_exchange=self.membership_exchange)

    def referrals(self):
        from .referrals_postgres import PostgresReferralTransaction
        return PostgresReferralTransaction(self)

    def support(self):
        from .support_postgres import PostgresSupportTransaction
        return PostgresSupportTransaction(self)

    def restricted_admin(self):
        from .restricted_admin_postgres import PostgresRestrictedAdminTransaction
        return PostgresRestrictedAdminTransaction(self)

    def restricted(self):
        from .restricted_postgres import PostgresRestrictedTransaction
        return PostgresRestrictedTransaction(self)

    def chat(self):
        from .chat_postgres import PostgresChatTransaction
        return PostgresChatTransaction(self)

    def routing(self):
        from .gateway_routing_postgres import PostgresRoutingTransaction
        return PostgresRoutingTransaction(self)

    def crl(self):
        from .crl_postgres import PostgresCRLTransaction
        return PostgresCRLTransaction(self)

    def registered(self, device):
        row = self.database.execute('SELECT support_id FROM device_support WHERE device=%s', (device,)).fetchone()
        if row is not None:
            return row['support_id']
        for attempt in range(32):
            random = ''.join(secrets.choice(ALPHABET) for index in range(8))
            support = 'FC-' + random[:4] + '-' + random[4:]
            row = self.database.execute(
                'INSERT INTO device_support(device,support_id) VALUES (%s,%s) '
                'ON CONFLICT (support_id) DO NOTHING RETURNING support_id', (device, support)).fetchone()
            if row is not None:
                return row['support_id']
        raise RuntimeError('Support ID allocation unavailable')


class PostgresEnrollment:
    def __init__(self, *, port, schema, password, membership_exchange=None):
        if (type(port) is not int or not 1024 <= port <= 65535 or type(schema) is not str
                or re.fullmatch(r'ha_enrollment_[0-9a-f]{32}', schema) is None
                or type(password) is not str or not password
                or membership_exchange is not None and not callable(membership_exchange)):
            raise ValueError('Invalid isolated enrollment store')
        self.port, self.schema, self.password = port, schema, password
        self.membership_exchange = membership_exchange

    def connect(self):
        import psycopg
        from psycopg.rows import dict_row
        return psycopg.connect(host='127.0.0.1', hostaddr='127.0.0.1', port=self.port,
            dbname='fc_ha_synthetic', user='fc_ha_synthetic', password=self.password,
            connect_timeout=3, sslmode='disable', options='-c search_path=pg_catalog', row_factory=dict_row)

    def configure(self, database):
        from psycopg import sql
        database.execute('SET TRANSACTION ISOLATION LEVEL READ COMMITTED, READ WRITE')
        database.execute("SET LOCAL statement_timeout='5s'")
        database.execute("SET LOCAL lock_timeout='3s'")
        database.execute("SET LOCAL idle_in_transaction_session_timeout='5s'")
        database.execute('SET LOCAL synchronous_commit=on')
        database.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(self.schema)))

    def initialize_synthetic(self):
        from psycopg import sql
        with self.connect() as database:
            self.configure(database)
            database.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(self.schema)))
            for statement in DDL:
                database.execute(statement)
            database.execute('INSERT INTO ha_enrollment_schema VALUES (%s,%s)', (SCHEMA_VERSION, PURPOSE))

    @contextmanager
    def transaction(self, *, readonly=False):
        if type(readonly) is not bool:
            raise ValueError('Invalid transaction mode')
        with self.connect() as database:
            self.configure(database)
            if readonly:
                database.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY')
            else:
                database.execute('SELECT pg_advisory_xact_lock(%s)', (LOCK_ID,))
            rows = database.execute('SELECT version,purpose FROM ha_enrollment_schema').fetchall()
            if rows != [dict(version=SCHEMA_VERSION, purpose=PURPOSE)]:
                raise RuntimeError('Enrollment rehearsal schema mismatch')
            yield PostgresEnrollmentTransaction(database, membership_exchange=self.membership_exchange)
